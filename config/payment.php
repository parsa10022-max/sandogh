<?php

return [

    /*
    |--------------------------------------------------------------------------
    | درگاه پرداخت
    |--------------------------------------------------------------------------
    |
    | مقادیر مجاز:
    | fake  - فقط محیط local و testing
    | sadad - پس از پیاده‌سازی کامل درگاه سداد
    |
    */

    'gateway' => env('PAYMENT_GATEWAY', 'fake'),

    /*
    |--------------------------------------------------------------------------
    | دامنه‌های مجاز هدایت درگاه
    |--------------------------------------------------------------------------
    |
    | دامنه‌ها را با کاما از هم جدا کن.
    | برای درگاه واقعی، دامنه رسمی درگاه را اضافه کن.
    |
    */

    'redirect_allowed_hosts' => array_filter(
        array_map(
            'trim',
            explode(
                ',',
                env(
                    'PAYMENT_ALLOWED_REDIRECT_HOSTS',
                    parse_url(
                        env('APP_URL', 'http://localhost'),
                        PHP_URL_HOST
                    ) ?: 'localhost'
                )
            )
        )
    ),

];
